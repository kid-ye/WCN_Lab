function run_all(which)
% RUN_ALL  Execute the WCN lab experiments and capture their genuine output.
%   run_all          runs Experiments 1-15
%   run_all([3 7])   runs only Experiments 3 and 7
%
% For every experiment this
%   * runs experiments/expNN.m exactly as written,
%   * records the Command Window output (diary),
%   * saves every figure, and the Command Window output, as PNG images in
%     output_images/ named <USN>_EXPNN_FIGk.png and <USN>_EXPNN_OUTPUT.png,
%   * writes generated/expNN_outputs.tex listing those images for main.tex.
% It also writes generated/expNN_code.m (the program plus the helper
% functions it calls, merged into one listing) for all 15 experiments.
% The USN comes only from config.m.

if nargin < 1, which = 1:15; end
root = fileparts(mfilename('fullpath'));

run(fullfile(root,'config.m'));           % defines USN
usn = strtrim(char(eval('USN')));
if isempty(usn), error('USN in config.m is empty.'); end

ctx.usn    = usn;
ctx.tag    = regexprep(usn,'[^A-Za-z0-9_-]','_');   % filename-safe USN
ctx.root   = root;
ctx.expdir = fullfile(root,'experiments');
ctx.outdir = fullfile(root,'output_images');
ctx.gendir = fullfile(root,'generated');
if ~exist(ctx.outdir,'dir'), mkdir(ctx.outdir); end
if ~exist(ctx.gendir,'dir'), mkdir(ctx.gendir); end
addpath(ctx.expdir);

% USN for the LaTeX title page and headers
fid = fopen(fullfile(ctx.gendir,'usn.tex'),'w');
fprintf(fid,'\\newcommand{\\USN}{%s}\n',tex_escape(usn));
if exist('OCTAVE_VERSION','builtin')
    fprintf(fid,'\\newcommand{\\RunEnv}{GNU Octave %s}\n',OCTAVE_VERSION);
else
    fprintf(fid,'\\newcommand{\\RunEnv}{MATLAB %s}\n',version);
end
fclose(fid);

write_merged_code(ctx);

set(0,'DefaultFigureVisible','off');
% Octave (unlike MATLAB) warns when a log plot contains zeros; MATLAB just
% omits them silently, so the warning is not part of the program's output.
warning('off','Octave:negative-data-log-axis');
for k = which
    fprintf('=== Experiment %02d ===\n',k);
    t0 = tic;
    run_experiment(k,ctx);
    fprintf('    done in %.1f s\n',toc(t0));
end
end

% -------------------------------------------------------------------------
function write_merged_code(ctx)
% One listing per experiment: the program followed by its helper functions.
helpers = cell(1,15);
helpers{1}  = {'erlangb','erlangb_traffic'};
helpers{9}  = {'prctile_local','ternary_local'};
helpers{12} = {'prctile_local'};
helpers{14} = {'bfs_hops','bfs_path'};
for k = 1:15
    files = [{sprintf('exp%02d',k)} helpers{k}];
    txt = '';
    for i = 1:numel(files)
        s = fileread(fullfile(ctx.expdir,[files{i} '.m']));
        s = regexprep(regexprep(s,'\r\n','\n'),'\n+$','');
        if i > 1, txt = [txt sprintf('\n\n')]; end %#ok<AGROW>
        txt = [txt s]; %#ok<AGROW>
    end
    fid = fopen(fullfile(ctx.gendir,sprintf('exp%02d_code.m',k)),'w');
    fprintf(fid,'%s\n',txt);
    fclose(fid);
end
end

% -------------------------------------------------------------------------
function run_experiment(k,ctx)
% The experiment scripts begin with "clc; clear; close all;", which wipes
% this function's workspace, so the context is parked in appdata.
setappdata(0,'wcn_ctx',struct('ctx',ctx,'k',k));
logf = fullfile(ctx.outdir,sprintf('%s_EXP%02d_OUTPUT.txt',ctx.tag,k));
if exist(logf,'file'), delete(logf); end
diary(logf);
run(fullfile(ctx.expdir,sprintf('exp%02d.m',k)));
diary off;
save_outputs(getappdata(0,'wcn_ctx'));
end

% -------------------------------------------------------------------------
function save_outputs(st)
ctx = st.ctx; k = st.k;
pfx = sprintf('%s_EXP%02d',ctx.tag,k);
old = dir(fullfile(ctx.outdir,sprintf('*_EXP%02d_*.png',k)));
for i = 1:numel(old), delete(fullfile(ctx.outdir,old(i).name)); end

figs = findobj(0,'type','figure');
[~,ix] = sort(double(figs)); figs = figs(ix);     % in creation order
files = {};
for i = 1:numel(figs)
    fn = sprintf('%s_FIG%d.png',pfx,i);
    set(figs(i),'PaperUnits','inches','PaperPosition',[0 0 8 5.2]);
    print(figs(i),fullfile(ctx.outdir,fn),'-dpng','-r200');
    files{end+1} = fn; %#ok<AGROW>
end
close all;

% Command Window output rendered as an image
logf = fullfile(ctx.outdir,[pfx '_OUTPUT.txt']);
txt  = clean_log(fileread(logf));
fid = fopen(logf,'w'); fprintf(fid,'%s',txt); fclose(fid);
con = sprintf('%s_OUTPUT.png',pfx);
render_text(txt,fullfile(ctx.outdir,con));

% LaTeX fragment for main.tex (figures are numbered k.1, k.2, ... by LaTeX)
fid = fopen(fullfile(ctx.gendir,sprintf('exp%02d_outputs.tex',k)),'w');
fprintf(fid,'%% Generated by run_all.m -- do not edit.\n');
fprintf(fid,'\\consoleoutput{output_images/%s}\n',con);
for i = 1:numel(files)
    fprintf(fid,'\\figureoutput{output_images/%s}\n',files{i});
end
fclose(fid);
end

% -------------------------------------------------------------------------
function render_text(txt,fname)
lines = regexp(txt,'\r?\n','split');
while ~isempty(lines) && isempty(strtrim(lines{end})), lines(end) = []; end
nl = max(numel(lines),1);
wd = 10; ht = 0.35 + 0.15*nl;
f = figure('Visible','off','Color','w','Units','inches','Position',[0 0 wd ht]);
a = axes('Parent',f,'Position',[0 0 1 1],'Visible','off','XLim',[0 1],'YLim',[0 1]);
text(0.025,1-0.18/ht,lines,'Parent',a,'Interpreter','none','FontName','Consolas',...
     'FontSize',9,'VerticalAlignment','top','HorizontalAlignment','left');
set(f,'PaperUnits','inches','PaperPosition',[0 0 wd ht]);
print(f,fname,'-dpng','-r300');
close(f);
end

% -------------------------------------------------------------------------
function t = clean_log(t)
t = regexprep(t,'\x1B\[[0-9;?]*[A-Za-z]','');   % terminal escape codes from clc
t = regexprep(t,'[\x00-\x08\x0B\x0C\x0E-\x1F]','');
t = regexprep(t,'\r\n','\n');
t = regexprep(t,'^\n+','');
end

% -------------------------------------------------------------------------
function s = tex_escape(s)
s = regexprep(s,'([\\{}$&#^_%~])','\\$1');
end
